#!/usr/bin/env node
/**
 * build-city-places.js — the city gazetteer the browser needs, and nothing else.
 *
 *   node tools/build-city-places.js
 *
 * WHY THIS IS ITS OWN FILE, AND ITS OWN TOOL.
 *
 * The station cards say where a station broadcasts from — "Sacramento,
 * California" rather than "Five-Fold", which told a reader nothing. The city is
 * already on every station's bases; the state or country is not, and it lives
 * in the `cities` table of data/broadcast-bases.json.
 *
 * It could not simply be threaded through station-bases.json, because
 * tools/build-broadcast-bases.js currently refuses to write at all: eleven
 * international stations have no bases assigned, and that generator treats a
 * station with nowhere to broadcast from as a hard error. That is the right
 * call for the roster and the wrong reason for the cards to stay broken, so
 * this writes the gazetteer on its own.
 *
 * IT MUST NOT BECOME A REQUIREMENT OF THE NIGHTLY BUILD. build-home-data.js
 * runs on the VPS, which carries no `data/` directory — AGENTS.md is explicit
 * that a tools file growing a new top-level require breaks the cron for every
 * station. So this tool reads data/ and writes public/data/, and the consumer
 * treats the result as OPTIONAL: no file, no KJ_CITIES, cards fall back to the
 * bare city name. Nothing breaks in the dark.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const IN = path.join(ROOT, 'data', 'broadcast-bases.json');
const OUT = path.join(ROOT, 'public', 'data', 'city-places.json');

let doc;
try { doc = JSON.parse(fs.readFileSync(IN, 'utf8')); }
catch (e) { console.error('cannot read ' + path.relative(ROOT, IN) + ' — ' + e.message); process.exit(1); }

const cities = doc.cities || {};
const places = {};
const missing = [];

for (const [name, rec] of Object.entries(cities)) {
  if (rec && rec.place) places[name] = rec.place;
  else missing.push(name + (rec && rec.cc ? ' [' + rec.cc + ']' : ''));
}

const out = {
  schema: 'kj.city.places/1',
  note: [
    'City -> the state (US) or country (everywhere else) printed after it on a',
    'station card. Generated by tools/build-city-places.js from the `cities`',
    'table in data/broadcast-bases.json, which is the editorial source.',
    'Optional at read time: a page with no gazetteer prints the bare city.',
  ],
  generated: new Date().toISOString().slice(0, 19).replace('T', ' '),
  places,
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n', 'utf8');

console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + Object.keys(places).length + ' cities');
if (missing.length) {
  console.log('  no state or country yet: ' + missing.join(', '));
  console.log('  add a "place" to those entries in data/broadcast-bases.json');
}
